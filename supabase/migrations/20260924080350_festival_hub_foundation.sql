  public.festival_sessions_id_seq to authenticated;

create policy "public can read published festival hubs"
on public.festival_hubs for select to anon, authenticated
using (
  lifecycle in ('published', 'archived')
  or exists (
    select 1 from public.app_admins
    where user_id = (select auth.uid()) and role = 'owner'
  )
);

create policy "public can read visible festival collections"
on public.festival_collections for select to anon, authenticated
using (
  exists (
    select 1 from public.festival_hubs h
    where h.id = festival_id and h.lifecycle in ('published', 'archived')
  )
  and exists (
    select 1 from public.learning_lists l
    where l.id = learning_list_id and l.visibility = 'public'
  )
  or exists (
    select 1 from public.app_admins
    where user_id = (select auth.uid()) and role = 'owner'
  )
);

create policy "public can read visible festival sessions"
on public.festival_sessions for select to anon, authenticated
using (
  exists (
    select 1 from public.festival_hubs h
    where h.id = festival_id and h.lifecycle in ('published', 'archived')
  )
  or exists (
    select 1 from public.app_admins
    where user_id = (select auth.uid()) and role = 'owner'
  )
);

create policy "public can read visible festival session collections"
on public.festival_session_collections for select to anon, authenticated
using (
  exists (
    select 1
    from public.festival_sessions s
    join public.festival_hubs h on h.id = s.festival_id
    join public.festival_collections c
      on c.id = festival_collection_id and c.festival_id = festival_session_collections.festival_id
    join public.learning_lists l on l.id = c.learning_list_id
    where s.id = session_id
      and s.festival_id = festival_session_collections.festival_id
      and h.lifecycle in ('published', 'archived')
      and l.visibility = 'public'
  )
  or exists (
    select 1 from public.app_admins
    where user_id = (select auth.uid()) and role = 'owner'
  )
);

create policy "public can read active festival settings"
on public.festival_settings for select to anon, authenticated
using (
  mode_enabled
  and exists (
    select 1 from public.festival_hubs h
    where h.id = selected_festival_id and h.lifecycle = 'published'
  )
  or exists (
    select 1 from public.app_admins
    where user_id = (select auth.uid()) and role = 'owner'
  )
);

