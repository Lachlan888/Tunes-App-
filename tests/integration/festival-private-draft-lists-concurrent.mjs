// Disposable local PostgreSQL race test. It is opt-in because it starts a
// temporary server; no remote connection or production write is involved.
// RUN_POSTGRES_CONCURRENCY_TEST=1 node tests/integration/festival-private-draft-lists-concurrent.mjs
import assert from "node:assert/strict"
import { spawn } from "node:child_process"
import { mkdtemp, readFile, readdir, rm } from "node:fs/promises"
import { createServer } from "node:net"
import { tmpdir } from "node:os"
import { join } from "node:path"

if (process.env.RUN_POSTGRES_CONCURRENCY_TEST !== "1") {
  console.log("SKIP: set RUN_POSTGRES_CONCURRENCY_TEST=1 to run the local PostgreSQL race test")
  process.exit(0)
}

function command(commandName, args, input = "") {
  return new Promise((resolve, reject) => {
    const child = spawn(commandName, args, { stdio: ["pipe", "pipe", "pipe"] })
    let stdout = ""
    let stderr = ""
    child.stdout.on("data", (chunk) => { stdout += chunk })
    child.stderr.on("data", (chunk) => { stderr += chunk })
    child.on("error", reject)
    child.on("close", (code) => resolve({ code, stdout, stderr }))
    child.stdin.end(input)
  })
}

async function requireSuccess(commandName, args, input = "") {
  const result = await command(commandName, args, input)
  assert.equal(result.code, 0, `${commandName} failed: ${result.stderr}`)
  return result
}

const postgresServer = await command("postgres", ["--version"]).catch(() => null)
if (!postgresServer || postgresServer.code !== 0) {
  console.log("SKIP: a local PostgreSQL server binary is required for the concurrency test")
  process.exit(0)
}

function startPsql(args) {
  const child = spawn("psql", args, { stdio: ["pipe", "pipe", "pipe"] })
  let stdout = ""
  let stderr = ""
  let settled = false
  child.stdout.on("data", (chunk) => { stdout += chunk })
  child.stderr.on("data", (chunk) => { stderr += chunk })
  const done = new Promise((resolve, reject) => {
    child.on("error", reject)
    child.on("close", (code) => {
      settled = true
      resolve({ code, stdout, stderr })
    })
  })
  return { child, done, output: () => ({ stdout, stderr, settled }) }
}

async function waitForOutput(process, expected) {
  const deadline = Date.now() + 5_000
  while (!process.output().stdout.includes(expected)) {
    if (process.output().settled || Date.now() >= deadline) {
      throw new Error(`Timed out waiting for ${JSON.stringify(expected)}; stderr: ${process.output().stderr}`)
    }
    await new Promise((resolve) => setTimeout(resolve, 10))
  }
}

async function availablePort() {
  const server = createServer()
  await new Promise((resolve) => server.listen(0, "127.0.0.1", resolve))
  const address = server.address()
  assert.ok(address && typeof address === "object")
  await new Promise((resolve, reject) => server.close((error) => error ? reject(error) : resolve()))
  return address.port
}

const directory = await mkdtemp(join(tmpdir(), "nff27-postgres-"))
const dataDirectory = join(directory, "data")
const port = await availablePort()
const psqlArgs = ["-X", "-qAt", "-v", "ON_ERROR_STOP=1", "-U", "nff27_test", "-h", directory, "-p", String(port), "-d", "postgres"]
let started = false

try {
  await requireSuccess("initdb", ["-D", dataDirectory, "-A", "trust", "-U", "nff27_test"])
  await requireSuccess("pg_ctl", ["-D", dataDirectory, "-o", `-k ${directory} -p ${port}`, "-w", "start"])
  started = true

  const psql = (sql) => requireSuccess("psql", psqlArgs, sql)
  await psql(`
    create role anon;
    create role authenticated;
    create table public.festival_hubs (id bigint primary key, lifecycle text not null);
    create table public.learning_lists (id bigint primary key, visibility text not null);
    create table public.festival_collections (
      id bigint generated by default as identity primary key,
      festival_id bigint not null references public.festival_hubs(id),
      learning_list_id bigint not null references public.learning_lists(id)
    );
    insert into public.festival_hubs values (1, 'draft'), (2, 'draft');
    insert into public.learning_lists values (11, 'public'), (12, 'public');
    insert into public.festival_collections(festival_id, learning_list_id) values (1, 11), (2, 12);
  `)

  const migrations = new URL("../../supabase/migrations/", import.meta.url)
  const guardMigrations = (await readdir(migrations))
    .filter((name) => (
      name.endsWith("_allow_private_draft_festival_lists.sql") ||
      name.endsWith("_prevent_private_festival_lists_on_released_hubs.sql") ||
      name.endsWith("_serialize_private_festival_list_transitions.sql")
    ))
    .sort()
  assert.equal(guardMigrations.length, 3)
  for (const migration of guardMigrations) {
    await psql(await readFile(new URL(migration, migrations), "utf8"))
  }

  const publishFirst = startPsql(psqlArgs)
  publishFirst.child.stdin.write("begin; update public.festival_hubs set lifecycle = 'published' where id = 1 returning lifecycle;\n")
  await waitForOutput(publishFirst, "published")
  const privateSecond = startPsql(psqlArgs)
  privateSecond.child.stdin.end("update public.learning_lists set visibility = 'private' where id = 11;\n")
  publishFirst.child.stdin.end("commit;\n")
  assert.equal((await publishFirst.done).code, 0)
  const privateAfterPublish = await privateSecond.done
  assert.notEqual(privateAfterPublish.code, 0)
  assert.match(privateAfterPublish.stderr, /private festival lists require a Draft hub/i)
  assert.equal((await psql("select lifecycle || ':' || (select visibility from public.learning_lists where id = 11) from public.festival_hubs where id = 1;")).stdout.trim(), "published:public")

  const privateFirst = startPsql(psqlArgs)
  privateFirst.child.stdin.write("begin; update public.learning_lists set visibility = 'private' where id = 12 returning visibility;\n")
  await waitForOutput(privateFirst, "private")
  const publishSecond = startPsql(psqlArgs)
  publishSecond.child.stdin.end("update public.festival_hubs set lifecycle = 'published' where id = 2;\n")
  privateFirst.child.stdin.end("commit;\n")
  assert.equal((await privateFirst.done).code, 0)
  const publishAfterPrivate = await publishSecond.done
  assert.notEqual(publishAfterPrivate.code, 0)
  assert.match(publishAfterPrivate.stderr, /private festival lists require public repertoire/i)
  assert.equal((await psql("select lifecycle || ':' || (select visibility from public.learning_lists where id = 12) from public.festival_hubs where id = 2;")).stdout.trim(), "draft:private")

  console.log("PASS: concurrent festival lifecycle and list visibility changes preserve private-draft boundaries")
} finally {
  if (started) await command("pg_ctl", ["-D", dataDirectory, "-m", "immediate", "stop"])
  await rm(directory, { recursive: true, force: true })
}
