// Disposable PostgreSQL test. No credentials, remote connection or production writes.
// PGLITE_MODULE=/absolute/path/to/pglite/dist/index.js node tests/integration/festival-private-draft-lists.mjs
import assert from "node:assert/strict"
import { readFile, readdir } from "node:fs/promises"

const { PGlite } = await import(process.env.PGLITE_MODULE)
const db = new PGlite()

try {
  await db.exec(`
    create role anon;
    create role authenticated;
    create table public.festival_hubs (id bigint primary key, lifecycle text not null);
    create table public.learning_lists (id bigint primary key, visibility text not null);
    create table public.festival_collections (
      id bigint generated by default as identity primary key,
      festival_id bigint not null references public.festival_hubs(id),
      learning_list_id bigint not null references public.learning_lists(id)
    );
    insert into public.festival_hubs values (1, 'draft'), (2, 'published'), (3, 'archived');
    insert into public.learning_lists values (10, 'private'), (11, 'public');
  `)

  const migrations = new URL("../../supabase/migrations/", import.meta.url)
  const migration = (await readdir(migrations)).find((name) => name.endsWith("_allow_private_draft_festival_lists.sql"))
  assert.ok(migration, "the lifecycle guard migration must exist")
  await db.exec(await readFile(new URL(migration, migrations), "utf8"))

  await db.query("insert into public.festival_collections(festival_id, learning_list_id) values (1, 10)")
  await db.query("insert into public.festival_collections(festival_id, learning_list_id) values (1, 11), (2, 11), (3, 11)")
  await assert.rejects(
    db.query("insert into public.festival_collections(festival_id, learning_list_id) values (2, 10)"),
    /private festival lists require a Draft hub/i
  )
  await assert.rejects(
    db.query("insert into public.festival_collections(festival_id, learning_list_id) values (3, 10)"),
    /private festival lists require a Draft hub/i
  )
  assert.deepEqual(
    (await db.query("select festival_id, learning_list_id from public.festival_collections order by festival_id, learning_list_id")).rows,
    [
      { festival_id: 1, learning_list_id: 10 },
      { festival_id: 1, learning_list_id: 11 },
      { festival_id: 2, learning_list_id: 11 },
      { festival_id: 3, learning_list_id: 11 },
    ]
  )
  console.log("PASS: Draft hubs retain private repertoire; published and archived hubs require public repertoire")
} finally {
  await db.close()
}
