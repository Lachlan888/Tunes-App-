// Run only in a disposable PGlite database. No network or application credentials.
// PGLITE_MODULE=/absolute/path/to/pglite/dist/index.js node tests/integration/formal-review-idempotency.mjs
import assert from "node:assert/strict"
import { readFile } from "node:fs/promises"

const { PGlite } = await import(process.env.PGLITE_MODULE)
const db = new PGlite()
const owner = "00000000-0000-0000-0000-000000000001"
const other = "00000000-0000-0000-0000-000000000002"

await db.exec(`
  create role authenticated;
  create schema auth;
  create table auth.users(id uuid primary key);
  create function auth.uid() returns uuid language sql stable as
  $$ select nullif(current_setting('test.user_id', true), '')::uuid $$;

  create table public.review_events(
    id bigint generated by default as identity primary key,
    user_piece_id bigint not null,
    outcome text not null,
    resulting_stage integer not null
  );
  create table public.user_pieces(
    id bigint primary key,
    user_id uuid not null,
    piece_id bigint not null,
    stage integer,
    next_review_due date,
    status text not null
  );
  create table public.profiles(id uuid primary key, practice_diary_enabled boolean default false);
  create table public.practice_note_categories(id bigint primary key, user_id uuid, is_active boolean);
  create table public.practice_foci(id bigint primary key, user_id uuid, status text);
  create table public.practice_focus_tunes(user_id uuid, focus_id bigint, piece_id bigint, unique(focus_id, piece_id));
  create table public.practice_days(
    id bigint generated by default as identity primary key,
    user_id uuid,
    practice_date date,
    updated_at timestamptz default now(),
    unique(user_id, practice_date)
  );
  create table public.practice_events(
    id bigint generated by default as identity primary key,
    user_id uuid, practice_day_id bigint, piece_id bigint, review_event_id bigint,
    event_type text, source_type text, counted_as_review boolean
  );
  create table public.practice_notes(
    id bigint generated by default as identity primary key,
    user_id uuid, practice_day_id bigint, practice_event_id bigint, piece_id bigint,
    review_event_id bigint, category_id bigint, focus_id bigint, body text
  );
  create table public.user_known_pieces(
    id bigint generated by default as identity primary key,
    user_id uuid, piece_id bigint, unique(user_id, piece_id)
  );
  create table public.user_activity_events(
    id bigint generated by default as identity primary key,
    user_id uuid, event_type text, piece_id bigint
  );
  create table public.user_daily_streaks(
    user_id uuid, local_date date, due_count integer, revision_done boolean,
    practice_done boolean, updated_at timestamptz, unique(user_id, local_date)
  );
  create table public.user_streak_stats(
    user_id uuid primary key,
    current_revision_streak integer, longest_revision_streak integer,
    current_practice_streak integer, longest_practice_streak integer,
    last_reconciled_date date, updated_at timestamptz
  );
  insert into auth.users values ('${owner}'), ('${other}');
  insert into profiles(id) values ('${owner}'), ('${other}');
  insert into user_pieces(id,user_id,piece_id,stage,next_review_due,status) values
    (11,'${owner}',101,4,'2026-09-25','learning'),
    (22,'${other}',202,4,'2026-09-25','learning');
`)

for (const migration of [
  "../../supabase/migrations/20260607000000_complete_formal_review_rpc.sql",
  "../../supabase/migrations/20260607010000_fix_complete_formal_review_piece_id_ambiguity.sql",
  "../../supabase/migrations/20260926062804_scope_formal_review_event_idempotency.sql",
]) {
  await db.exec(await readFile(new URL(migration, import.meta.url), "utf8"))
}

await db.exec(`
  grant usage on schema public, auth to authenticated;
  grant all on all tables in schema public to authenticated;
  grant usage, select on all sequences in schema public to authenticated;
  set role authenticated;
  set test.user_id='${owner}';
`)

const query = async (sql, args = []) => (await db.query(sql, args)).rows
const review = async (key, userPieceId) => (await query(
  "select * from complete_formal_review($1,$2,'solid',null,null,null,false,'2026-09-26')",
  [key, userPieceId]
))[0]

const key = "formal-review:fixture:owner:1"
const first = await review(key, 11)
const retry = await review(key, 11)
assert.equal(first.applied, true)
assert.equal(retry.applied, false)
assert.equal(retry.review_event_id, first.review_event_id)
assert.equal((await query("select count(*)::int as count from review_events"))[0].count, 1)

await assert.rejects(review("formal-review:fixture:cross-account", 22), /Practice tune not found/)
assert.equal((await query("select count(*)::int as count from review_events"))[0].count, 1)

await query("select set_config('test.user_id',$1,false)", [other])
const otherResult = await review(key, 22)
assert.equal(otherResult.applied, true, "submission keys are isolated by account")
assert.equal((await query("select count(*)::int as count from review_events"))[0].count, 2)

await db.close()
console.log("PASS: formal-review same-key retry, account isolation and cross-account rejection")
