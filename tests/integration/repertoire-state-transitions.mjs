// Run only in a disposable PGlite database. No network or application credentials.
// PGLITE_MODULE=/absolute/path/to/pglite/dist/index.js node tests/integration/repertoire-state-transitions.mjs
import assert from "node:assert/strict"
import { readFile, readdir } from "node:fs/promises"

const { PGlite } = await import(process.env.PGLITE_MODULE)
const db = new PGlite()
const owner = "00000000-0000-0000-0000-000000000001"
const other = "00000000-0000-0000-0000-000000000002"

await db.exec(`
  create role authenticated;
  create role anon;
  create schema auth;
  create table auth.users(id uuid primary key);
  create function auth.uid() returns uuid language sql stable as
  $$ select nullif(current_setting('test.user_id', true), '')::uuid $$;

  create table public.pieces(id bigint primary key);
  create table public.user_pieces(
    id bigint generated by default as identity primary key,
    user_id uuid not null references auth.users(id) on delete cascade,
    piece_id bigint not null references public.pieces(id) on delete cascade,
    status text not null,
    stage integer,
    next_review_due date,
    unique(user_id, piece_id)
  );
  create table public.user_known_pieces(
    id bigint generated by default as identity primary key,
    user_id uuid not null references auth.users(id) on delete cascade,
    piece_id bigint not null references public.pieces(id) on delete cascade,
    unique(user_id, piece_id)
  );
  create table public.review_events(
    id bigint generated by default as identity primary key,
    user_piece_id bigint not null references public.user_pieces(id) on delete cascade,
    date timestamptz not null default now(),
    outcome text not null,
    resulting_stage integer not null
  );
  create table public.user_activity_events(
    id bigint generated by default as identity primary key,
    user_id uuid not null,
    event_type text not null,
    piece_id bigint
  );

  insert into auth.users values ('${owner}'), ('${other}');
  insert into public.pieces values (101), (202), (303);
  insert into public.user_known_pieces(user_id,piece_id) values ('${other}',202);

  alter table public.user_pieces enable row level security;
  alter table public.user_known_pieces enable row level security;
  alter table public.review_events enable row level security;
  create policy "owners can read user_pieces" on public.user_pieces for select to authenticated using (user_id = auth.uid());
  create policy "owners can insert user_pieces" on public.user_pieces for insert to authenticated with check (user_id = auth.uid());
  create policy "owners can delete user_pieces" on public.user_pieces for delete to authenticated using (user_id = auth.uid());
  create policy "owners can read user_known_pieces" on public.user_known_pieces for select to authenticated using (user_id = auth.uid());
  create policy "owners can insert user_known_pieces" on public.user_known_pieces for insert to authenticated with check (user_id = auth.uid());
  create policy "owners can delete user_known_pieces" on public.user_known_pieces for delete to authenticated using (user_id = auth.uid());
  create policy "owners can read review_events" on public.review_events for select to authenticated using (
    exists (select 1 from public.user_pieces up where up.id = review_events.user_piece_id and up.user_id = auth.uid())
  );
`)

const migrations = await readdir(new URL("../../supabase/migrations/", import.meta.url))
const transitionMigration = migrations.find((name) => name.endsWith("_atomic_repertoire_state.sql"))
assert.ok(transitionMigration, "atomic repertoire-state migration exists")
await db.exec(
  await readFile(
    new URL(`../../supabase/migrations/${transitionMigration}`, import.meta.url),
    "utf8"
  )
)

await db.exec(`
  grant usage on schema public, auth to authenticated;
  grant select, insert, update, delete on public.user_pieces, public.user_known_pieces, public.review_events, public.user_activity_events to authenticated;
  grant usage, select on all sequences in schema public to authenticated;
  grant execute on function public.enrol_piece_in_practice(bigint, date) to authenticated;
  grant execute on function public.mark_piece_known(bigint) to authenticated;
  set role authenticated;
  set test.user_id='${owner}';
`)

const query = async (sql, args = []) => (await db.query(sql, args)).rows

await query("insert into user_known_pieces(user_id,piece_id) values ($1,101)", [owner])
assert.equal((await query("select enrol_piece_in_practice(101,'2026-10-05') as result"))[0].result, "started")
assert.equal((await query("select enrol_piece_in_practice(101,'2026-10-05') as result"))[0].result, "already_in_practice")
assert.equal((await query("select count(*)::int as count from user_known_pieces"))[0].count, 0)
assert.equal((await query("select count(*)::int as count from user_pieces"))[0].count, 1)
assert.equal((await query("select count(*)::int as count from user_activity_events"))[0].count, 0, "enrolment creates no public practice activity")

const userPiece = (await query("select id from user_pieces where piece_id=101"))[0]
await query("insert into review_events(user_piece_id,outcome,resulting_stage) values ($1,'solid',2)", [userPiece.id])
assert.equal((await query("select mark_piece_known(101) as result"))[0].result, "marked_known")
assert.equal((await query("select mark_piece_known(101) as result"))[0].result, "already_known")
const review = (await query("select user_piece_id,user_id,piece_id from review_events"))[0]
assert.equal(review.user_piece_id, null, "state movement detaches rather than deletes review history")
assert.equal(review.user_id, owner)
assert.equal(Number(review.piece_id), 101)
assert.equal((await query("select count(*)::int as count from user_activity_events where event_type='marked_known'"))[0].count, 1)
await assert.rejects(
  query("insert into review_events(user_piece_id,user_id,piece_id,outcome,resulting_stage) values (null,$1,202,'solid',2)", [owner]),
  /Review identity must come from a practice tune/
)

await query("insert into user_known_pieces(user_id,piece_id) values ($1,303)", [owner])
await assert.rejects(
  query("insert into user_pieces(user_id,piece_id,status) values ($1,303,null)", [owner]),
  /null value in column "status"/
)
assert.equal((await query("select count(*)::int as count from user_known_pieces where piece_id=303"))[0].count, 1, "a failed target insert rolls back the opposite-state delete")

assert.equal((await query("select enrol_piece_in_practice(202,'2026-10-05') as result"))[0].result, "started")
assert.equal((await query("select count(*)::int as count from user_known_pieces where user_id=$1", [other]))[0].count, 0, "RLS hides another account from direct reads")

await query("select set_config('test.user_id',$1,false)", [other])
assert.equal((await query("select mark_piece_known(202) as result"))[0].result, "already_known")
assert.equal((await query("select count(*)::int as count from user_known_pieces where user_id=$1", [other]))[0].count, 1, "one account cannot transition another account's state")

await db.exec("set role anon;")
await assert.rejects(
  query("select enrol_piece_in_practice(101,'2026-10-05')"),
  /permission denied for function enrol_piece_in_practice/
)

await db.close()
console.log("PASS: atomic/idempotent repertoire transitions, enrolment semantics, review preservation and ownership")
